        // 15. The pilot's exam: many small pieces ride the wind round the wall.
        level(
            Chapter.WIND,
            """
            ......
            ......
            ...P..
            ......
            .*....
            .#####
            .*....
            S.....
            """,
            wind = Vec(0, 1),
        ),
    )
}
