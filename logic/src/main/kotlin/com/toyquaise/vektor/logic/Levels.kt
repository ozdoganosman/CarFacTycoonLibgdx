        level(
            Chapter.WIND,
            """
            ......
            ......
            P...#.
            #.*...
            ...#.#
            ....*S
            ....#.
            ......
            """,
            wind = Vec(-1, 0),
        ),
        // 14. An east wind and a tight tank: five units exactly.
        level(
            Chapter.WIND,
            """
            ......
            .....P
            #.*#.#
            .*....
            ......
            S#...#
            ......
            ......
            """,
            wind = Vec(1, 0),
